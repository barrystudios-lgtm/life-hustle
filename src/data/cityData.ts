export function getCityLocations(region: string = 'NG', city: string = 'Lagos', country: string = 'Nigeria'): LocationVenue[] {
  const normCity = (city || '').toLowerCase();
  const normCountry = (country || '').toLowerCase();
  const normReg = (region || '').toUpperCase();

  // 1. Nigeria locations
  if (normReg === 'NG' || normCountry.includes('nigeria')) {
    if (
      normCity.includes('abuja') ||
      normCity.includes('maitama') ||
      normCity.includes('wuse') ||
      normCity.includes('garki')
    ) {
      return ABUJA_CITY_LOCATIONS;
    }
    if (
      normCity.includes('rivers') ||
      normCity.includes('port harcourt') ||
      normCity.includes('choba') ||
      normCity.includes('trans-amadi')
    ) {
      return PORT_HARCOURT_CITY_LOCATIONS;
    }
    // Default Nigeria is Lagos / Lekki
    return LAGOS_CITY_LOCATIONS;
  }

  // 2. US - California
  if (
    normCity.includes('california') ||
    normCity.includes('silicon valley') ||
    normCity.includes('los angeles') ||
    normCity.includes('san francisco') ||
    normCity.includes('beverly hills') ||
    normCity.includes('hollywood') ||
    normCity.includes('venice')
  ) {
    return CALIFORNIA_CITY_LOCATIONS;
  }

  // 3. Default US - New York Metropolis
  return US_CITY_LOCATIONS;
}

